#!/usr/bin/env python3
import seekpath
from ase.io import read
import numpy as np

# 1. 读取结构 (支持 POSCAR, cif, xsf 等)
# 这里的 'POSCAR' 是你的文件名
structure = read('POSCAR')

# 2. 转换数据格式为 seekpath 所需的 (cell, positions, numbers)
# 注意：positions 必须是分数坐标 (scaled positions)
cell = structure.get_cell()
positions = structure.get_scaled_positions()
numbers = structure.get_atomic_numbers()

system = (cell, positions, numbers)

# 3. 运行 seekpath 获取路径
# 'hpkot' 是默认的标准路径生成规则
res = seekpath.get_path(system, with_time_reversal=True)

# 4. 打印结果或生成文件
print(f"Spacegroup: {res['spacegroup_international']} (No. {res['spacegroup_number']})")
print("-" * 30)
print("Standardized Primitive Cell generated. You MUST use this for calculation!")

# 输出 K点坐标
print("\nHigh Symmetry Points:")
for label, coords in res['point_coords'].items():
    print(f"{label}: {coords}")

# 输出路径
print("\nSuggested Path:")
path_list = []
for segment in res['path']:
    path_list.append(f"{segment[0]}-{segment[1]}")
print(" -> ".join(path_list))

# -------------------------------------------------------
# 5. 自动生成 KPOINTS 文件内容 (Line-mode)
# -------------------------------------------------------
filename = "KPOINTS_seekpath"
with open(filename, 'w') as f:
    f.write("K-Path generated by SeeK-path\n")
    f.write("20\n") # 节点间插值点数
    f.write("Line-mode\n")
    f.write("Reciprocal\n")
    for segment in res['path']:
        start_label = segment[0]
        end_label = segment[1]
        start_coord = res['point_coords'][start_label]
        end_coord = res['point_coords'][end_label]
        
        f.write(f"{start_coord[0]:.6f} {start_coord[1]:.6f} {start_coord[2]:.6f} ! {start_label}\n")
        f.write(f"{end_coord[0]:.6f} {end_coord[1]:.6f} {end_coord[2]:.6f} ! {end_label}\n")
        f.write("\n")

print(f"\n[Done] K-path written to file: {filename}")

# 6. 保存标准化后的原胞 (非常重要！)
# seekpath 建议使用它转换后的结构，否则 K点可能对应不上
from ase import Atoms
new_atoms = Atoms(numbers=res['primitive_types'],
                  scaled_positions=res['primitive_positions'],
                  cell=res['primitive_lattice'],
                  pbc=True)
new_atoms.write("POSCAR_std", format='vasp', vasp5=True)
print("[Done] Standardized structure written to: POSCAR_std")


